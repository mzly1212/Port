def ang_diff_deg(a, b):
    """两角的最短几何夹角 (0° ~ 180°), 全模块统一的环形角度运算"""
    return abs((a - b + 180) % 360 - 180)


def norm_deg(a):
    """角度归一化至 [0, 360)"""
    return a % 360


def geo_heading_of(map_heading_deg):
    """地图航向(数学角约定)转地理航向"""
    return (90 - map_heading_deg) % 360
