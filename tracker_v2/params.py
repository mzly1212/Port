TYPE_FIX_RATIO = 0.8         # 已锁定类型的纠正占比门槛
FIXED_FACILITY_SUB_TYPES = {13, 14}  # 候工亭/锁销框=13, 舱盖板=14

# ==========================================
# 八、固定设施位置锚定 (v1 已验证机制, 原样移植)
# ==========================================
