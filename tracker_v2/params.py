# -*- coding: utf-8 -*-
"""
params.py — tracker_v2 全部可调参数 (唯一权威来源)

与 v1 的本质区别: 参数按「处理层」分组, 组间无隐式耦合。
v1 的历史教训是 "缝合距离/去重窗口/方向死区三者调一个要看三个"——
那是因为车道系状态 (s/方向/变道) 与关联逻辑互相纠缠。
v2 中:
  - 关联层只看 2D 物理空间 (马氏距离 + 重连窗口)
  - 运动层只有卡尔曼 + 航向估计器, 不知道车道存在
  - 车道绑定是纯输出注释层, 改它的参数不可能影响关联
现场调优只改这个文件。
"""

# ==========================================
# 一、关联层 (Association)
#   量测 <-> 航迹的双向匹配。ID 跳变缝合、分裂去重、
#   断联重连在 v2 中坍缩为同一个几何关联问题。
# ==========================================
ASSOC_CHI2_GATE = 13.82      # 马氏距离平方门限 (2 自由度卡方 99.9%)
ASSOC_REJOIN_BASE = 30.0     # 断联重连距离基线(米): dist < base + v*gap
ASSOC_REJOIN_MAX = 70.0      # 重连距离上限(米)
ASSOC_HARD_DIST = 70.0       # 任何关联的硬距离上限(米)
ASSOC_ID_BONUS = 2.0         # 同 object_id 的代价减免 (马氏距离单位):
                             # 感知稳定时优先延续同一 ID, 仅作软偏好不做硬约束
ASSOC_MIN_SPEED_VETO = 1.0   # 航向否决要求航迹已建立的速度下限(m/s)
ASSOC_HEADING_VETO = 150.0   # 航向近乎正对才否决 (对向车签名)。
                             # ⚠ 历史教训: 90°~120° 会误杀感知交界处
                             # 同车双报 (航向差可达 120°+), 只拦 >150°
ASSOC_FLIP_MARK = 120.0      # 单帧航向跳变阈值(度): 物理上不可能,
                             # 是雷达前后混淆的专属签名
ASSOC_FLIP_WINDOW_MS = 4000  # 出现过翻转标记后, 该车航向在此窗口内
                             # 不作为否决依据 (前后混淆豁免)
ASSOC_STALE_GAP_MS = 150     # 航迹断联超过此时长才启用重连窗口:
                             # 新鲜航迹 (上帧刚命中) 只走卡方门限,
                             # 防止远处无关新车被重连窗口吞并
ASSOC_SPLIT_CLAIM = 10.0     # 同帧分裂认领距离(米): 新量测距新鲜航迹小于此值
                             # 视为同车双报候选 (仍需过航向否决/设施隔离)
                             # ⚠ 历史教训: v1 全量认领 18m, 收紧到 12m 会在
                             # 感知交界处漏缝合, 此处只对"新鲜航迹"收紧

# ==========================================
# 二、运动滤波层 (Kalman CV + 航向估计)
# ==========================================
KF_SIGMA_R = 0.5             # 量测噪声标准差(米): 融合感知位置噪声
KF_SIGMA_A = 0.6             # 过程噪声加速度标准差(m/s²): 平稳港口交通
KF_NIS_GATE = 13.82          # NIS 门限: 超出则膨胀量测噪声做鲁棒更新,
                             # 位置跳变 (交接偏差/重连) 平滑收敛而非瞬移
HEADING_ALPHA = 0.2          # 雷达航向环形低通系数 (免疫 0°/360° 交界)
HEADING_NOISE_JUMP = 45.0    # 连续追踪下单帧航向突变拒绝门限(度)

# ==========================================
# 三、断联推演层 (Coasting)
# ==========================================
COAST_DECAY_TAU = 3.0        # 盲区速度指数衰减时间常数(秒)
COAST_MIN_SPEED = 0.3        # 衰减下限(m/s): 低于视为静止
COAST_ONLANE_MS = 8000       # 在轨航迹盲区超时
COAST_OFFLANE_MS = 2500      # 离道航迹盲区超时
COAST_FACILITY_MS = 10000    # 固定设施断检超时 (防过车遮挡闪烁)
COAST_TENTATIVE_MS = 1000    # 未确认航迹断检超时 (快速消灭噪点)
PREDICTED_FLAG_MS = 500      # 盲区超过此时长才对前端标 is_predicted

# ==========================================
# 四、生命周期与航迹合并
# ==========================================
CONFIRM_HITS = 2             # 航迹确认所需累计命中帧数
NEW_TRACK_GRACE_MS = 300     # 新航迹保护期: 此内不输出 (滤除闪现噪点)
MERGE_DIST = 8.0             # 航迹合并状态距离门限(米)
MERGE_STATIC_DIST = 3.0      # 双方均低速时的合并距离收紧(米): 静止车队
                             # 间距通常 >5m, 同车双报通常 <3m
MERGE_V_DIFF = 3.0           # 航迹合并速度差门限(m/s)
MERGE_HEADING_VETO = 150.0   # 两航迹运动方向正对则不合并 (对向车)

# ==========================================
# 五、方向裁决 (车道系切向符号 + 兜底)
#   输入是 KF 速度矢量在车道切向上的投影, 无需历史回归,
#   不存在 "清历史导致方向丢失" 的失效模式。
# ==========================================
DIR_DEADZONE = 0.8           # 死区: 切向投影速度低于此值不参与判定(m/s)
DIR_CONFIRM_N = 5            # 方向翻转需连续确认帧数
DIR_UNKNOWN_FLIP = 150.0     # 方向未知期: 雷达航向与车道反向超过此值翻转
MOTION_HEADING_MIN_SPEED = 0.8  # 运动矢导航向可用的速度下限(m/s)
OFFLANE_STATIC_SPEED = 0.5   # 离道静止判定速度(m/s): 静止则冻结航向
OFFLANE_MIN_MOTION = 1.5     # 离道运动矢量纠正的最小位移当量(m/s 持续)
OFFLANE_HEADING_ERRATIC = 60.0  # 航向杂乱度阈值(度): 1 秒内两两夹角
HEADING_MOTION_CONFLICT = 90.0  # 航向与运动方向不符的判定角(度)
HEADING_MAX_RATE = 45.0      # 离道输出航向限转速(度/秒)

# ==========================================
# 六、车道绑定层 (纯输出注释, 不回馈运动状态)
# ==========================================
LANE_BIND_BASE_DIST = 2.5    # 车道匹配基础距离阈值(米)
LANE_BIND_DYNAMIC = 3.0      # 速度动态放宽上限(米): v*0.1, 封顶
LANE_BIND_HEADING_THRESH = 45.0  # 匹配航向约束角(度)
LANE_BIND_HEADING_RELAX = 90.0   # 老车道/极近距离的航向约束放宽角
LANE_HYSTERESIS_M = 1.5      # 老车道粘滞护城河(米): 防相邻车道画龙
LANE_HYSTERESIS_FRAMES = 5   # 车道变更确认帧数
LANE_ANGLE_WEIGHT = 0.2      # 航向软惩罚权重 (米/度)

# ==========================================
# 七、车型投票锁定 (v1 已验证机制, 原样移植)
# ==========================================
